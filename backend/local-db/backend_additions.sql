-- 로컬 시험용 DB(solpay_backend)에만 적용한다. 공용 DB 에는 실행하지 않는다.
--
-- 팀 DB 형식 CSV(카드서비스_DB_1년)로 만든 로컬 DB 에는 백엔드 코드가 기대하는 것 4가지가 없다.
-- 백엔드 엔티티(User, Card, UserCard, Schedule)를 보고 맞춘 것이라, 공용 DB 의 실제 정의와 세부(기본값·제약)는 다를 수 있다.
--
--   docker exec solpay-db createdb -U solpay_app solpay_backend
--   docker exec solpay-db sh -c 'pg_dump -U solpay_app solpay | psql -U solpay_app -q -d solpay_backend'
--   docker exec -i solpay-db psql -U solpay_app -d solpay_backend < backend/local-db/backend_additions.sql

-- 1) 회원 권한 (User.role: USER / ADMIN)
ALTER TABLE users ADD COLUMN IF NOT EXISTS role varchar(20) NOT NULL DEFAULT 'USER';

-- 2) 카드 이미지 주소 (Card.imageUrl)
ALTER TABLE cards ADD COLUMN IF NOT EXISTS image_url text;

-- 3) 번호 자동 증가 (회원가입·카드 등록이 번호 없이 INSERT 한다)
DO $$
BEGIN
    IF (SELECT is_identity FROM information_schema.columns
         WHERE table_schema = 'public' AND table_name = 'users' AND column_name = 'user_id') = 'NO' THEN
        ALTER TABLE users ALTER COLUMN user_id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
    IF (SELECT is_identity FROM information_schema.columns
         WHERE table_schema = 'public' AND table_name = 'user_cards' AND column_name = 'user_card_id') = 'NO' THEN
        ALTER TABLE user_cards ALTER COLUMN user_card_id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END $$;
SELECT setval(pg_get_serial_sequence('users', 'user_id'), (SELECT max(user_id) FROM users));
SELECT setval(pg_get_serial_sequence('user_cards', 'user_card_id'), (SELECT max(user_card_id) FROM user_cards));

-- 4) 일정 (Schedule)
CREATE TABLE IF NOT EXISTS schedules (
    schedule_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       bigint      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    schedule_date date        NOT NULL,
    kind          varchar(10) NOT NULL,          -- SITUATION / PLACE
    types         varchar(100),
    category      varchar(30),
    title         varchar(40),
    start_time    varchar(5),
    end_time      varchar(5),
    memo          varchar(80),
    created_at    timestamp   NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS schedules_user_date_idx ON schedules (user_id, schedule_date);
