-- 공용 RDS(solpay DB)에 final 백엔드가 기대하는 것 2가지를 더한다 (2026-11-23).
--
-- 왜: 백엔드는 ddl-auto: validate 라 엔티티의 표·칸이 DB 에 없으면 켜지지 않는다.
--     공용 RDS 에는 Card.imageUrl 의 cards.image_url 칸과 Schedule 엔티티의 schedules 표가 없다.
--     (로컬 시험 DB 는 local-db/backend_additions.sql 로 이미 맞춰 두었다. 아래 정의는 그것과 같다.)
--
-- 누가: 표 주인인 마스터 계정(postgres)으로 실행한다. app_ai 계정은 읽기 전용이라 실행할 수 없다.
-- 여러 번 실행해도 안전하다 (IF NOT EXISTS). 기존 데이터는 바꾸지 않는다.
--
-- 실행 예 (로컬 도커의 psql 을 빌려 쓴다. 비밀번호는 실행할 때 묻는다):
--   docker cp backend/shared-db/add_schedules_and_image_url.sql solpay-db:/tmp/rds_add.sql
--   docker exec -it solpay-db psql "host=<RDS 주소> port=5432 dbname=solpay user=postgres sslmode=require" -v ON_ERROR_STOP=1 -f /tmp/rds_add.sql
--   또는 IntelliJ·DBeaver 의 DB 콘솔에 이 파일 내용을 붙여 넣어 실행한다.

BEGIN;

-- 1) 카드 이미지 주소 (Card.imageUrl). 값은 비워 둔다: 비어 있으면 백엔드가 static/card-images/{카드번호}.webp 를 쓴다 (CardImages).
ALTER TABLE public.cards ADD COLUMN IF NOT EXISTS image_url text;

-- 2) 일정 (Schedule 엔티티)
CREATE TABLE IF NOT EXISTS public.schedules (
    schedule_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       bigint      NOT NULL REFERENCES public.users (user_id) ON DELETE CASCADE,
    schedule_date date        NOT NULL,
    kind          varchar(10) NOT NULL,          -- SITUATION / PLACE
    types         varchar(100),                  -- 상황 일정 종류(쉼표 구분)
    category      varchar(30),                   -- 장소 일정 업종 코드 (categories.category)
    title         varchar(40),                   -- 직접 입력 이름
    start_time    varchar(5),                    -- "HH:mm"
    end_time      varchar(5),                    -- "HH:mm" (24:00 허용)
    memo          varchar(80),
    created_at    timestamp   NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS schedules_user_date_idx ON public.schedules (user_id, schedule_date);

-- 다른 public 표와 같게 AI 계정은 읽기만 (AI 엔진은 지금 이 표를 읽지 않지만 권한 모양을 맞춘다)
GRANT SELECT ON public.schedules TO app_ai;

COMMIT;

-- 확인: 둘 다 'ok' 가 나와야 한다
SELECT CASE WHEN EXISTS (SELECT 1 FROM information_schema.columns
                          WHERE table_schema = 'public' AND table_name = 'cards' AND column_name = 'image_url')
            THEN 'ok' ELSE 'MISSING' END AS cards_image_url,
       CASE WHEN to_regclass('public.schedules') IS NOT NULL THEN 'ok' ELSE 'MISSING' END AS schedules_table;
