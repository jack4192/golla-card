-- 웹 푸시(바탕화면 웹앱 아침 일정 알림) 기기 등록 표 push_subscriptions 를 만든다 (2026-11-25).
--
-- 왜: 아이폰 바탕화면 웹앱은 휴대폰이 스스로 알림을 예약할 수 없어, 백엔드가 매일 7시·'지금 알림 받기' 때 웹 푸시를 보낸다.
--     앱이 알림을 켜면 브라우저가 준 구독 정보(endpoint·p256dh·auth)를 여기에 저장한다.
--     백엔드는 이 표를 JPA 엔티티가 아니라 JdbcClient 로 다뤄서, 표가 없어도 백엔드는 켜진다(알림 기능만 오류).
--
-- 여러 번 실행해도 안전하다 (IF NOT EXISTS). 기존 데이터는 바꾸지 않는다.
-- 누가: 공용 RDS 는 마스터 계정(postgres)으로 실행한다.
--
-- 실행 예 (로컬 도커의 psql 을 빌려 쓴다. 비밀번호는 실행할 때 묻는다):
--   docker cp backend/shared-db/add_push_subscriptions.sql solpay-db:/tmp/rds_push.sql
--   docker exec -it solpay-db psql "host=<RDS 주소> port=5432 dbname=solpay user=postgres sslmode=require" -v ON_ERROR_STOP=1 -f /tmp/rds_push.sql

BEGIN;

CREATE TABLE IF NOT EXISTS public.push_subscriptions (
    push_subscription_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              bigint      NOT NULL REFERENCES public.users (user_id) ON DELETE CASCADE,
    endpoint             text        NOT NULL UNIQUE,
    p256dh               text        NOT NULL,
    auth                 text        NOT NULL,
    created_at           timestamptz NOT NULL DEFAULT now(),
    last_sent_at         timestamptz
);
CREATE INDEX IF NOT EXISTS push_subscriptions_user_idx ON public.push_subscriptions (user_id);

COMMENT ON TABLE public.push_subscriptions IS '웹 푸시 구독(바탕화면 웹앱 아침 일정 알림). endpoint 는 기기마다 고유';

COMMIT;
