-- 개인 DB 의 쓰기용 표 (2026-11-19 결정).
-- 팀 DB 23개 표(public, 카드서비스_DB_1년 schema.sql)는 읽기만 하고, Spring 이 붙기 전까지 FastAPI 가 여기(app)에 쓴다.
-- 팀원과 합친 공동 DB 로 갈 때는 이 표들을 Spring 이 쓰는 표로 옮긴다.
-- 적용: uv run python -m scripts.setup_local_db  (여러 번 실행해도 된다)

create schema if not exists app;

-- 챗봇이 사용자 확인을 받아 저장한 규칙 (engine.rules 의 JSON 형식)
create table if not exists app.user_rules (
    rule_id     bigint generated by default as identity primary key,
    user_id     bigint      not null references public.users (user_id) on delete cascade,
    rule        jsonb       not null,
    created_seq integer     not null default 0,
    active      boolean     not null default true,
    created_at  timestamptz not null default now()
);
create index if not exists user_rules_active on app.user_rules (user_id) where active;

-- 챗봇 규칙 초안: 대기 → 저장(user_rules 에 추가) 또는 취소
create table if not exists app.chat_rule_drafts (
    draft_id   bigint generated by default as identity primary key,
    user_id    bigint       not null references public.users (user_id) on delete cascade,
    session_id varchar(64),
    rule       jsonb        not null,
    summary    varchar(200) not null,
    status     varchar(10)  not null default 'pending' check (status in ('pending', 'saved', 'cancelled')),
    created_at timestamptz  not null default now(),
    decided_at timestamptz
);

-- 실적 채우기 방식 (최초 선택 initial, 사용자 확정 confirmed)
create table if not exists app.strategy_selections (
    user_id    bigint primary key references public.users (user_id) on delete cascade,
    strategy   varchar(20) not null,
    source     varchar(20) not null check (source in ('initial', 'confirmed')),
    metadata   jsonb,
    updated_at timestamptz not null default now()
);

-- 결제 화면 추천 기록 (챗봇 '추천 이유 설명'이 읽는다)
create table if not exists app.recommendation_logs (
    recommendation_id bigint generated by default as identity primary key,
    user_id        bigint      not null references public.users (user_id) on delete cascade,
    recommended_at timestamptz not null,
    version        varchar(20),
    scenario_mode  varchar(30),
    base_card      bigint,
    scenarios      jsonb,
    scores         jsonb,
    ranking        jsonb,
    display_count  integer,
    reason_code    varchar(30),
    messages       jsonb,
    swapped        boolean,
    rule_applied   bigint
);
create index if not exists recommendation_logs_user on app.recommendation_logs (user_id, recommendation_id desc);

-- 하루 일정: 암호문으로만 저장하고 지난 날은 엔진이 지운다 (engine.crypto, SOLPAY_DATA_KEY)
create table if not exists app.schedules (
    user_id bigint not null references public.users (user_id) on delete cascade,
    day     date   not null,
    payload bytea  not null,
    primary key (user_id, day)
);

-- 신규 카드 추천 기록 (3일 간격 판단)
create table if not exists app.card_recommendations (
    id             bigint generated by default as identity primary key,
    user_id        bigint      not null references public.users (user_id) on delete cascade,
    recommended_at timestamptz not null,
    card_id        bigint      not null references public.cards (card_id),
    trigger        varchar(30),
    gain           integer
);

-- 로컬 시연(가상 POS)에서 더한 결제. 운영에서는 Spring 이 public.payments 에 쓴다.
create table if not exists app.demo_payments (
    payment_id       bigint primary key,
    user_id          bigint      not null references public.users (user_id) on delete cascade,
    user_card_id     bigint      not null references public.user_cards (user_card_id),
    merchant_id      bigint,
    category         varchar(30) not null references public.categories (category),
    channel          varchar(20) not null,
    card_select_mode varchar(20) not null,
    amount           integer     not null check (amount > 0),
    paid_at          timestamptz not null,
    synced_at        timestamptz
);
create index if not exists demo_payments_user on app.demo_payments (user_id, paid_at);
