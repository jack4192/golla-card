-- =====================================================================
-- 카드 추천 서비스 스키마 (PostgreSQL 14+)
-- 실행: psql -d <DB이름> -f schema.sql
-- 테이블 18개 (추천·규칙·챗봇·알림·설정 테이블은 구현 확정 후 추가). 생성 순서는 외래키(FK) 의존 순서입니다.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 사용자·인증
-- ---------------------------------------------------------------------
CREATE TABLE users (
    user_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(50)  NOT NULL,
    birth_date      DATE         NOT NULL,
    phone           VARCHAR(20)  NOT NULL UNIQUE,
    email           VARCHAR(100) NOT NULL UNIQUE,
    password_hash   VARCHAR(100) NOT NULL,
    mydata_agreed   BOOLEAN,                 -- NULL=아직 응답 안 함, TRUE=동의, FALSE=철회/거부
    location_agreed BOOLEAN,                 -- NULL=아직 응답 안 함, TRUE=동의, FALSE=철회/거부
    workplace_name  VARCHAR(100)
);

-- ---------------------------------------------------------------------
-- 2. 공통 코드
-- ---------------------------------------------------------------------
CREATE TABLE categories (
    category      VARCHAR(30) PRIMARY KEY,    -- 업종 코드 (CAFE, CONVENIENCE ...)
    category_name VARCHAR(30) NOT NULL        -- 한글 업종명
);

CREATE TABLE merchant_aliases (
    alias_name VARCHAR(100) PRIMARY KEY,      -- 표기 변형 (예: 메가커피)
    brand_name VARCHAR(100) NOT NULL          -- 정규화된 브랜드명 (예: 메가MGC커피)
);

-- ---------------------------------------------------------------------
-- 3. 카드 카탈로그·혜택
-- ---------------------------------------------------------------------
CREATE TABLE cards (
    card_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issuer    VARCHAR(20)  NOT NULL,
    card_name VARCHAR(100) NOT NULL,
    card_type VARCHAR(10)  NOT NULL CHECK (card_type IN ('CREDIT', 'CHECK')),
    annual_fee_domestic INTEGER NOT NULL DEFAULT 0 CHECK (annual_fee_domestic >= 0),  -- 국내전용 연회비(원)
    annual_fee_overseas INTEGER NOT NULL DEFAULT 0 CHECK (annual_fee_overseas >= 0),  -- 해외겸용 연회비(원)
    description VARCHAR(200),                                                          -- 카드 한 줄 소개
    UNIQUE (issuer, card_name)
);

CREATE TABLE card_perks (
    perk_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id     BIGINT       NOT NULL REFERENCES cards (card_id) ON DELETE CASCADE,
    perk_name   VARCHAR(50)  NOT NULL,
    description VARCHAR(300) NOT NULL,
    UNIQUE (card_id, perk_name)
);

CREATE TABLE card_tiers (
    tier_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id     BIGINT  NOT NULL REFERENCES cards (card_id) ON DELETE CASCADE,
    tier_no     INTEGER NOT NULL CHECK (tier_no >= 0),       -- 0 = 실적 미달
    min_amount  INTEGER NOT NULL CHECK (min_amount >= 0),    -- 이 구간의 전월 이용금액 하한(원)
    total_limit INTEGER CHECK (total_limit >= 0),            -- 카드 월 통합 한도 (NULL=없음)
    UNIQUE (card_id, tier_no),
    UNIQUE (card_id, tier_id)                                -- user_cards 복합 FK용
);

CREATE TABLE benefit_groups (
    group_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id    BIGINT       NOT NULL REFERENCES cards (card_id) ON DELETE CASCADE,
    group_name VARCHAR(50)  NOT NULL,
    UNIQUE (card_id, group_name)
);

CREATE TABLE benefit_group_tiers (
    group_tier_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id      BIGINT  NOT NULL REFERENCES benefit_groups (group_id) ON DELETE CASCADE,
    tier_id       BIGINT  NOT NULL REFERENCES card_tiers (tier_id) ON DELETE CASCADE,
    monthly_limit INTEGER NOT NULL CHECK (monthly_limit > 0),
    UNIQUE (group_id, tier_id)
);

CREATE TABLE benefits (
    benefit_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id        BIGINT       NOT NULL REFERENCES cards (card_id) ON DELETE CASCADE,
    group_id       BIGINT       REFERENCES benefit_groups (group_id) ON DELETE SET NULL,
    benefit_name   VARCHAR(100) NOT NULL,
    benefit_kind   VARCHAR(10)  NOT NULL CHECK (benefit_kind IN ('DISCOUNT', 'POINT', 'CASHBACK')),
    value_type     VARCHAR(10)  NOT NULL CHECK (value_type IN ('RATE', 'FIXED', 'PER_LITER')),
    limit_basis    VARCHAR(10)  NOT NULL CHECK (limit_basis IN ('BENEFIT', 'USAGE')),
    pay_type       VARCHAR(10)  CHECK (pay_type IN ('PAY', 'NOPAY', 'SOLPAY', 'KBPAY', 'SAMSUNGPAY', 'NHPAY')),
    min_pay_amount INTEGER      CHECK (min_pay_amount > 0),
    time_from      TIME,
    time_to        TIME,
    days           VARCHAR(20),
    daily_count    INTEGER      CHECK (daily_count > 0),
    description    VARCHAR(300),                -- 고객에게 보여줄 제외·유의사항
    CHECK ((time_from IS NULL) = (time_to IS NULL))
);

CREATE TABLE benefit_targets (
    target_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benefit_id    BIGINT       NOT NULL REFERENCES benefits (benefit_id) ON DELETE CASCADE,
    category      VARCHAR(30)  NOT NULL REFERENCES categories (category),
    merchant_name VARCHAR(100)             -- NULL이면 업종 전체
);

CREATE TABLE benefit_tiers (
    benefit_tier_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benefit_id        BIGINT        NOT NULL REFERENCES benefits (benefit_id) ON DELETE CASCADE,
    tier_id           BIGINT        NOT NULL REFERENCES card_tiers (tier_id) ON DELETE CASCADE,
    value             NUMERIC(10, 2) NOT NULL CHECK (value > 0), -- RATE는 %, FIXED는 원, PER_LITER는 원/ℓ
    monthly_limit     INTEGER       CHECK (monthly_limit > 0),     -- 영역 월 한도 (NULL=없음)
    monthly_count     INTEGER       CHECK (monthly_count > 0),     -- 월 이용 가능 횟수 (NULL=제한 없음)
    per_payment_limit INTEGER       CHECK (per_payment_limit > 0), -- 건당 한도 (NULL=없음)
    UNIQUE (benefit_id, tier_id)
);

-- ---------------------------------------------------------------------
-- 4. 가맹점·프로모션·단말기
-- ---------------------------------------------------------------------
CREATE TABLE merchants (
    merchant_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_name VARCHAR(100)  NOT NULL,          -- 정규화된 브랜드명
    branch_name   VARCHAR(50),
    category      VARCHAR(30)   NOT NULL REFERENCES categories (category),
    latitude      NUMERIC(9, 6) NOT NULL,
    longitude     NUMERIC(9, 6) NOT NULL,
    in_mall       BOOLEAN       NOT NULL DEFAULT FALSE  -- TRUE=복합몰 입점 매장 ("몰 결제")
);

CREATE TABLE promotions (
    promotion_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id       BIGINT        REFERENCES cards (card_id) ON DELETE CASCADE,  -- NULL이면 카드 무관
    issuer        VARCHAR(20),                                                 -- 카드사 전체 대상 (card_id와 동시 지정 불가)
    merchant_id   BIGINT        REFERENCES merchants (merchant_id) ON DELETE CASCADE,  -- 특정 지점 한정
    promo_name    VARCHAR(100)  NOT NULL,
    category      VARCHAR(30)   REFERENCES categories (category),
    merchant_name VARCHAR(100),
    value_type    VARCHAR(10)   NOT NULL CHECK (value_type IN ('RATE', 'FIXED')),
    value         NUMERIC(10, 2) NOT NULL CHECK (value > 0),
    max_amount    INTEGER       CHECK (max_amount > 0),
    start_date    DATE          NOT NULL,
    end_date      DATE          NOT NULL,
    CHECK (start_date <= end_date),
    CHECK (card_id IS NULL OR issuer IS NULL)
);

CREATE TABLE terminals (
    terminal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id BIGINT      NOT NULL REFERENCES merchants (merchant_id) ON DELETE CASCADE,
    key_hash    VARCHAR(64) NOT NULL UNIQUE      -- 단말기 키의 SHA-256 해시
);

-- ---------------------------------------------------------------------
-- 5. 사용자 카드·결제
-- ---------------------------------------------------------------------
CREATE TABLE user_cards (
    user_card_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT  NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    card_id        BIGINT  NOT NULL REFERENCES cards (card_id),
    card_last4     CHAR(4) NOT NULL,
    target_tier_id BIGINT,                              -- 사용자가 채우려는 목표 구간
    UNIQUE (user_id, card_id),
    FOREIGN KEY (card_id, target_tier_id) REFERENCES card_tiers (card_id, tier_id)
);

CREATE TABLE payments (
    payment_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_card_id     BIGINT       NOT NULL REFERENCES user_cards (user_card_id) ON DELETE CASCADE,
    merchant_name    VARCHAR(100) NOT NULL,          -- 정규화된 브랜드명
    category         VARCHAR(30)  NOT NULL REFERENCES categories (category),
    amount           INTEGER      NOT NULL CHECK (amount > 0),
    paid_at          TIMESTAMP    NOT NULL,
    benefit_id       BIGINT       REFERENCES benefits (benefit_id) ON DELETE SET NULL,
    benefit_amount   INTEGER      NOT NULL DEFAULT 0 CHECK (benefit_amount >= 0),
    promotion_id     BIGINT       REFERENCES promotions (promotion_id) ON DELETE SET NULL,
    promotion_amount INTEGER      NOT NULL DEFAULT 0 CHECK (promotion_amount >= 0),
    approval_no      VARCHAR(10)  UNIQUE             -- 가상 POS 승인번호 (마이데이터 결제는 NULL)
);

CREATE TABLE payment_codes (
    code_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_card_id BIGINT      NOT NULL REFERENCES user_cards (user_card_id) ON DELETE CASCADE,
    code_hash    VARCHAR(64) NOT NULL UNIQUE,      -- 18자리 코드의 HMAC-SHA256 (원문 저장 안 함)
    expires_at   TIMESTAMP   NOT NULL,             -- 발급 + 60초
    status       VARCHAR(10) NOT NULL DEFAULT 'ISSUED' CHECK (status IN ('ISSUED', 'USED', 'VOID')),
    payment_id   BIGINT      UNIQUE REFERENCES payments (payment_id) ON DELETE SET NULL,
    CHECK (payment_id IS NULL OR status = 'USED')
);

CREATE TABLE pos_transactions (
    txn_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id    BIGINT      NOT NULL REFERENCES terminals (terminal_id) ON DELETE CASCADE,
    code_hash      VARCHAR(64) NOT NULL,           -- 입력된 코드의 HMAC (형식 오류 값 포함)
    amount         INTEGER     NOT NULL CHECK (amount > 0),
    requested_at   TIMESTAMP   NOT NULL,           -- 실제 시각
    payment_id     BIGINT      UNIQUE REFERENCES payments (payment_id) ON DELETE CASCADE,
    decline_reason VARCHAR(20) CHECK (decline_reason IN ('INVALID_FORMAT', 'NOT_ISSUED', 'ALREADY_USED', 'VOIDED', 'EXPIRED')),
    CHECK ((payment_id IS NULL) <> (decline_reason IS NULL))   -- 승인이면 payment_id, 거절이면 사유
);
