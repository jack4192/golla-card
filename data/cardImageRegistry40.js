export const findCardImageRecord = cardId =>
  CARD_IMAGE_REGISTRY_40.find(item => item.cardId === Number(cardId)) || null;

// For Expo Image, prefer downloaded/licensed local assets in production.
// A remote URI can be blocked by hotlink protection; test availability on web & iOS.
export const getRemoteCardImageSource = cardId => {
  const item = findCardImageRecord(cardId);
  return item?.imageUrl ? { uri: item.imageUrl } : null;
};

